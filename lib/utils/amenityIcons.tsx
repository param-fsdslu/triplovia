/** The icon that best matches an amenity's name (a check mark when none does) */
export function getAmenityIcon(name: string): LucideIcon {
  const key = name.toLowerCase().trim();
  return RULES.find(([pattern]) => pattern.test(key))?.[1] ?? CheckCircle2;
}
